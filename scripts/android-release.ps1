# Builds the signed Android release APK (64-bit ARM phones, Android 10+) into dist\.
# Needs: Android SDK + NDK, the aarch64-linux-android Rust target, and the signing key
# (src-tauri\gen\android\keystore.properties, see MOBILE.md "Signed release").
# Run from the repository root:  powershell -File scripts\android-release.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$sdk = if ($env:ANDROID_HOME) { $env:ANDROID_HOME } else { "$env:LOCALAPPDATA\Android\Sdk" }
$ndk = if ($env:NDK_HOME) { $env:NDK_HOME } else { (Get-ChildItem "$sdk\ndk" | Sort-Object Name | Select-Object -Last 1).FullName }
if (-not $env:JAVA_HOME) { $env:JAVA_HOME = 'C:\Program Files\Android\Android Studio\jbr' }
$env:ANDROID_HOME = $sdk
$env:NDK_HOME = $ndk
$bin = "$ndk\toolchains\llvm\prebuilt\windows-x86_64\bin"
$env:CC_aarch64_linux_android = "$bin\aarch64-linux-android29-clang.cmd"
$env:AR_aarch64_linux_android = "$bin\llvm-ar.exe"
$env:CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER = "$bin\aarch64-linux-android29-clang.cmd"

if (-not (Test-Path 'src-tauri\gen\android\keystore.properties')) {
  throw 'Missing src-tauri\gen\android\keystore.properties: create the signing key first (MOBILE.md, Signed release).'
}

# The phone's version (separate from desktop): Android only installs a higher versionCode.
$version = (Get-Content 'src-tauri\tauri.android.conf.json' -Raw | ConvertFrom-Json).version
$p = $version.Split('.') | ForEach-Object { [int]$_ }
$code = $p[0] * 1000000 + $p[1] * 1000 + $p[2]
@"
// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
tauri.android.versionName=$version
tauri.android.versionCode=$code
"@ | Set-Content -Encoding ascii 'src-tauri\gen\android\app\tauri.properties'

Write-Host "Agora for Android $version (versionCode $code)"
cargo build --release --target aarch64-linux-android -p agora --lib --features tauri/custom-protocol
if ($LASTEXITCODE -ne 0) { throw 'Rust build failed' }

# Tauri's own Android build links the library with a symbolic link, which Windows only allows in
# Developer Mode: copy it into place and let Gradle package and sign.
$libs = 'src-tauri\gen\android\app\src\main\jniLibs\arm64-v8a'
New-Item -ItemType Directory -Force $libs | Out-Null
Copy-Item 'target\aarch64-linux-android\release\libagora_lib.so' $libs -Force
Push-Location 'src-tauri\gen\android'
try {
  .\gradlew.bat assembleUniversalRelease -x rustBuildUniversalRelease
  if ($LASTEXITCODE -ne 0) { throw 'Gradle build failed' }
} finally { Pop-Location }

New-Item -ItemType Directory -Force 'dist' | Out-Null
$out = "dist\agora-android-$version.apk"
Copy-Item 'src-tauri\gen\android\app\build\outputs\apk\universal\release\app-universal-release.apk' $out -Force
Write-Host ("Signed APK: {0} ({1:N1} MB)" -f $out, ((Get-Item $out).Length / 1MB))
Write-Host "Publish it as a GitHub release tagged android-v$version, with the APK attached."
